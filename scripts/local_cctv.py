"""Prepare a local-CCTV evaluation dataset: extract frames, import annotations, run QA, assign group-wise splits.

    .venv\\Scripts\\python.exe scripts\\local_cctv.py extract    --dataset datasets\\local_cctv\\v1 --video cam3_0800.mp4 ^
        --camera-id cam3 --recording-id r0800 --recording-start-utc 2026-11-02T02:30:00Z --stride-seconds 2 --conditions day,dry
    .venv\\Scripts\\python.exe scripts\\local_cctv.py import-yolo --dataset datasets\\local_cctv\\v1 --labels export\\obj_train_data ^
        --classes export\\obj.names --annotator annotator_a --tool CVAT --tool-version 2.x
    .venv\\Scripts\\python.exe scripts\\local_cctv.py qa       --dataset datasets\\local_cctv\\v1 [--agreement]
    .venv\\Scripts\\python.exe scripts\\local_cctv.py split    --dataset datasets\\local_cctv\\v1 --group-by recording --seed 0

Everything is non-destructive: extract never overwrites a frame, import-yolo never overwrites an existing label file
(a conflicting file aborts the import), the manifest keeps its history, every import is appended to annotation_log.jsonl.
No frames or annotations are ever generated by this tool. See docs/ANVESH_LOCAL_CCTV_BENCHMARK.md.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from anvesh.training import local_cctv as lc  # noqa: E402


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def cmd_extract(a) -> int:
    import cv2

    root = Path(a.dataset)
    (root / "frames").mkdir(parents=True, exist_ok=True)
    manifest = lc.load_manifest(root) if (root / "manifest.json").is_file() else {
        "format": "anvesh-local-cctv/1", "classes": list(lc.LOCAL_CLASSES), "created_utc": _now(), "frames": []}
    existing = {r["frame_id"] for r in manifest["frames"]}
    video = Path(a.video)
    cap = cv2.VideoCapture(str(video))
    if not cap.isOpened():
        raise SystemExit(f"cannot open {video}")
    fps = cap.get(cv2.CAP_PROP_FPS) or 0.0
    if fps <= 0:
        raise SystemExit("video reports no frame rate; pass --fps")
    stride = max(1, round((a.stride_seconds or 1.0) * (a.fps or fps)))
    vsha = lc.sha256_file(video)
    added, idx = 0, 0
    while True:
        ok, frame = cap.read()
        if not ok or (a.max_frames and added >= a.max_frames):
            break
        if idx % stride == 0:
            fid = lc.make_frame_id(a.camera_id, a.recording_id, idx)
            if fid in existing:
                raise SystemExit(f"{fid} already in the manifest; refusing to overwrite (use a new --recording-id)")
            path = root / "frames" / f"{fid}.jpg"
            if path.exists():
                raise SystemExit(f"{path} exists; refusing to overwrite")
            cv2.imwrite(str(path), frame, [cv2.IMWRITE_JPEG_QUALITY, 95])
            h, w = frame.shape[:2]
            manifest["frames"].append({
                "frame_id": fid, "image": f"frames/{fid}.jpg", "width": w, "height": h, "image_sha256": lc.sha256_file(path),
                "camera_id": a.camera_id, "recording_id": a.recording_id, "recording_start_utc": a.recording_start_utc,
                "frame_index": idx, "frame_time_s": round(idx / (a.fps or fps), 3), "source_video": video.name,
                "source_video_sha256": vsha, "source_fps": a.fps or fps, "location": a.location,
                "conditions": [c for c in (a.conditions or "").split(",") if c], "labelled": False, "split": None})
            added += 1
        idx += 1
    cap.release()
    lc.save_manifest(root, manifest)
    print(f"extracted {added} frames (every {stride} source frames) into {root / 'frames'}; all unlabelled, no split yet")
    return 0


def _read_names(path: Path) -> list:
    return [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]


def cmd_import_yolo(a) -> int:
    root = Path(a.dataset)
    manifest = lc.load_manifest(root)
    names = _read_names(Path(a.classes))
    to_local, to_ignore = {}, set()
    for i, n in enumerate(names):
        key = n.strip().lower().replace(" ", "_").replace("-", "_")
        if key in lc.LOCAL_CLASSES:
            to_local[i] = lc.LOCAL_CLASSES.index(key)
        elif key in lc.IGNORE_NAMES:
            to_ignore.add(i)
        else:
            raise SystemExit(f"export class {n!r} (id {i}) is not one of {lc.LOCAL_CLASSES} or {lc.IGNORE_NAMES}; "
                             "relabel or rename it in the annotation tool (an unmapped class would silently become background)")
    by_id = {r["frame_id"]: r for r in manifest["frames"]}
    label_files = {p.stem: p for p in Path(a.labels).glob("*.txt")}
    stray = sorted(set(label_files) - set(by_id))
    if stray:
        raise SystemExit(f"{len(stray)} label file(s) match no frame in the manifest, e.g. {stray[:3]}; names must equal frame_id")
    second = a.role == "second"
    dest_labels = root / "labels_second" / a.annotator if second else root / "labels"
    dest_ignore = root / "ignore"
    plan = []
    for fid, f in label_files.items():
        rec = by_id[fid]
        rows, errs = lc.parse_yolo_rows(f.read_text(encoding="utf-8"), n_classes=len(names))
        if errs:
            raise SystemExit(f"{f.name}: {errs[:3]}")
        keep = [(to_local[c], *v) for c, *v in rows if c in to_local]
        ign = [(0, *v) for c, *v in rows if c in to_ignore]
        target = dest_labels / f"{fid}.txt"
        if target.exists():
            raise SystemExit(f"{target} already exists; refusing to overwrite an existing annotation "
                             "(import a corrected export under a new --annotator/--role second, or remove the file deliberately)")
        plan.append((rec, target, keep, ign))
    dest_labels.mkdir(parents=True, exist_ok=True)
    if not second:
        dest_ignore.mkdir(exist_ok=True)
    fmt = lambda rows: "".join(f"{c} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}\n" for c, cx, cy, w, h in rows)  # noqa: E731
    for rec, target, keep, ign in plan:
        target.write_text(fmt(keep), encoding="utf-8")  # an EMPTY file is meaningful: verified negative frame
        if not second:
            if ign:
                (dest_ignore / f"{rec['frame_id']}.txt").write_text(fmt(ign), encoding="utf-8")
            rec.update(labelled=True, annotator=a.annotator, annotation_tool=a.tool, annotation_tool_version=a.tool_version,
                       annotated_utc=_now(), reviewed=bool(a.reviewed))
    if not second:
        lc.save_manifest(root, manifest)
    with open(root / "annotation_log.jsonl", "a", encoding="utf-8") as log:
        log.write(json.dumps({"utc": _now(), "role": a.role, "annotator": a.annotator, "tool": a.tool, "tool_version": a.tool_version,
                              "labels_dir": str(a.labels), "frames": len(plan), "classes": names}) + "\n")
    print(f"imported {len(plan)} label files ({a.role}); frames without a file stay unlabelled and are excluded from metrics")
    return 0


def cmd_qa(a) -> int:
    root = Path(a.dataset)
    rep = lc.check_dataset(root, min_side_px=a.min_side_px)
    by_id = {r["frame_id"]: r for r in lc.load_manifest(root)["frames"]}
    if a.agreement:
        per_annot = {}
        for d in sorted((root / "labels_second").glob("*")) if (root / "labels_second").is_dir() else []:
            frames = []
            for f in d.glob("*.txt"):
                rec = by_id.get(f.stem)
                primary = root / "labels" / f.name
                if rec and primary.is_file():
                    ra, _ = lc.parse_yolo_rows(primary.read_text(encoding="utf-8"))
                    rb, _ = lc.parse_yolo_rows(f.read_text(encoding="utf-8"))
                    frames.append(lc.agreement(ra, rb, rec["width"], rec["height"]))
            per_annot[d.name] = lc.summarise_agreement(frames)
        rep["agreement"] = per_annot or "no labels_second/ data: inter-annotator agreement NOT measured"
    out = root / "qa_report.json"
    out.write_text(json.dumps(rep, indent=2), encoding="utf-8")
    print(json.dumps({"counts": rep["counts"], "errors": len(rep["errors"]), "warnings": len(rep["warnings"]),
                      "agreement": rep.get("agreement")}, indent=2))
    for e in rep["errors"][:20]:
        print("ERROR  ", e)
    for w in rep["warnings"][:10]:
        print("WARNING", w)
    print(f"full report: {out}")
    return 1 if rep["errors"] else 0


def cmd_split(a) -> int:
    root = Path(a.dataset)
    manifest = lc.load_manifest(root)
    if a.eval_only:
        mapping = {r["frame_id"]: "eval" for r in manifest["frames"]}
    else:
        fr = {"train": a.train, "val": a.val, "test": a.test}
        if abs(sum(fr.values()) - 1.0) > 1e-9:
            raise SystemExit("train+val+test fractions must sum to 1")
        mapping = lc.assign_splits(manifest["frames"], fr, a.seed, a.group_by)
    already = [r["frame_id"] for r in manifest["frames"] if r.get("split") and mapping[r["frame_id"]] != r["split"]]
    if already and not a.reassign:
        raise SystemExit(f"{len(already)} frames already have a different split; pass --reassign to change (the previous manifest is kept in manifest_history/)")
    for r in manifest["frames"]:
        r["split"] = mapping[r["frame_id"]]
    manifest["split_policy"] = {"group_by": a.group_by, "seed": a.seed, "eval_only": a.eval_only, "assigned_utc": _now()}
    lc.save_manifest(root, manifest)
    groups = {}
    for r in manifest["frames"]:
        groups.setdefault(r["split"], set()).add(lc.group_key(r, a.group_by))
    print({k: {"frames": sum(1 for r in manifest["frames"] if r["split"] == k), "groups": len(v)} for k, v in sorted(groups.items())})
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("extract")
    e.add_argument("--dataset", required=True)
    e.add_argument("--video", required=True)
    e.add_argument("--camera-id", required=True)
    e.add_argument("--recording-id", required=True)
    e.add_argument("--recording-start-utc", default=None, help="ISO-8601 UTC of the first video frame (needed for time-leakage audit)")
    e.add_argument("--stride-seconds", type=float, default=2.0, help="seconds between sampled frames (>= 1 recommended)")
    e.add_argument("--fps", type=float, default=None, help="override the container's frame rate")
    e.add_argument("--max-frames", type=int, default=None)
    e.add_argument("--conditions", default="", help="comma list, e.g. day,dry | night,rain")
    e.add_argument("--location", default=None)
    e.set_defaults(fn=cmd_extract)
    i = sub.add_parser("import-yolo")
    i.add_argument("--dataset", required=True)
    i.add_argument("--labels", required=True, help="directory of YOLO .txt files named <frame_id>.txt")
    i.add_argument("--classes", required=True, help="the export's class-name file (obj.names / classes.txt), one name per line")
    i.add_argument("--annotator", required=True)
    i.add_argument("--tool", required=True)
    i.add_argument("--tool-version", default="unknown")
    i.add_argument("--role", choices=("primary", "second"), default="primary")
    i.add_argument("--reviewed", action="store_true", help="a second person reviewed these labels")
    i.set_defaults(fn=cmd_import_yolo)
    q = sub.add_parser("qa")
    q.add_argument("--dataset", required=True)
    q.add_argument("--min-side-px", type=float, default=8.0)
    q.add_argument("--agreement", action="store_true")
    q.set_defaults(fn=cmd_qa)
    s = sub.add_parser("split")
    s.add_argument("--dataset", required=True)
    s.add_argument("--group-by", choices=lc.GROUP_BY, default="recording")
    s.add_argument("--train", type=float, default=0.6)
    s.add_argument("--val", type=float, default=0.2)
    s.add_argument("--test", type=float, default=0.2)
    s.add_argument("--eval-only", action="store_true", help="put every frame in split 'eval' (benchmark-only footage, never trained on)")
    s.add_argument("--seed", type=int, default=0)
    s.add_argument("--reassign", action="store_true")
    s.set_defaults(fn=cmd_split)
    a = ap.parse_args(argv)
    return a.fn(a)


if __name__ == "__main__":
    raise SystemExit(main())
